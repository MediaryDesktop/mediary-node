#!/usr/bin/env node

/**
 * Derive the auth input limits from the cloud contract.
 *
 * The server decides how long a password has to be; the client only decides
 * how to say so before the round-trip. Reading the numbers out of the spec
 * keeps the message honest when the server's mind changes, which a second
 * hand-maintained copy of them never managed.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))

const SPEC = resolve(HERE, '../../../mediary-contracts/openapi/cloud.openapi.json')
const OUT = resolve(HERE, '../src/features/auth/validation/limits.gen.ts')

const spec = JSON.parse(readFileSync(SPEC, 'utf8'))
const schemas = spec.components?.schemas ?? {}

function property(schemaName, propertyName) {
	const property = schemas[schemaName]?.properties?.[propertyName]

	if (!property) {
		throw new Error(`${schemaName}.${propertyName} is missing from the contract`)
	}

	return property
}

function constraint(schemaName, propertyName, keyword) {
	const value = property(schemaName, propertyName)[keyword]

	if (typeof value !== 'number') {
		throw new Error(`${schemaName}.${propertyName} declares no numeric ${keyword}`)
	}

	return value
}

function codeLength(schemaName, propertyName) {
	const pattern = property(schemaName, propertyName).pattern ?? ''
	const digits = /\[0-9\]\{(\d+)\}/u.exec(pattern)

	if (!digits) {
		throw new Error(`${schemaName}.${propertyName} has no fixed-length digit pattern`)
	}

	return Number(digits[1])
}

const limits = {
	MIN_PASSWORD_LENGTH: constraint('RegisterInputBody', 'password', 'minLength'),
	MAX_PASSWORD_LENGTH: constraint('RegisterInputBody', 'password', 'maxLength'),
	MIN_DISPLAY_NAME: constraint('RegisterInputBody', 'display_name', 'minLength'),
	MAX_DISPLAY_NAME: constraint('RegisterInputBody', 'display_name', 'maxLength'),
	MAX_EMAIL_LENGTH: constraint('RegisterInputBody', 'email', 'maxLength'),
	CODE_LENGTH: codeLength('ConfirmEmailInputBody', 'code')
}

const body = [
	'// Generated by scripts/gen-auth-limits.mjs from the cloud contract.',
	'// Run `npm run api:types` after the contract changes; do not edit by hand.',
	'',
	...Object.entries(limits).map(([name, value]) => `export const ${name} = ${value}`),
	''
].join('\n')

writeFileSync(OUT, body)

console.log(`wrote ${OUT} (${Object.keys(limits).length} limits)`)
